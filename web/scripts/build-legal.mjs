// Regenerates src/content/legal/generated.ts from the .md files. Run: node scripts/build-legal.mjs
import fs from "node:fs";
const dir = new URL("../src/content/legal/", import.meta.url);
const names = ["terms", "privacy", "prohibited", "safety"];
let out = "// Generated by scripts/build-legal.mjs. Edit the .md files, then rerun.\n";
for (const n of names) out += `export const ${n} = ${JSON.stringify(fs.readFileSync(new URL(n + ".md", dir), "utf8"))};\n`;
fs.writeFileSync(new URL("generated.ts", dir), out);
